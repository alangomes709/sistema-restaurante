public class Fornecedor {
    int idFornecedor;
    String nome;
    String ingredientes;
    String data;
    String contato;

    public Fornecedor(int idFornecedor, String nome, String ingredientes, String data, String contato) {
        this.idFornecedor = idFornecedor;
        this.nome = nome;
        this.ingredientes = ingredientes;
        this.data = data;
        this.contato = contato;
    }
    
}
